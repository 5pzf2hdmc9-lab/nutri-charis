export default function LegalModal({ docKey, onClose }) {
  const doc = DOCS[docKey];

  useEffect(() => {
    if (!doc) return undefined;
    const onKey = (e) => {
      if (e.key === 'Escape') onClose?.();
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [doc, onClose]);

  if (!doc) return null;

  return (
    <div
      role="dialog"
      aria-modal="true"
      aria-labelledby="legal-modal-title"
      className="glass-modal-backdrop"
      style={{
        position: 'fixed',
        inset: 0,
        zIndex: 700,
        display: 'flex',
        alignItems: 'center',
        justifyContent: 'center',
        padding: '16px'
      }}
      onClick={onClose}
    >
      <div
        className="luxury-card glass-elevated"
        style={{
          width: '100%',
          maxWidth: '640px',
          maxHeight: '85vh',
          overflow: 'auto',
          padding: '24px',
          animation: 'fadeInSlide 0.22s ease'
        }}
        onClick={(e) => e.stopPropagation()}
      >
        <div style={{ display: 'flex', alignItems: 'flex-start', justifyContent: 'space-between', gap: '12px', marginBottom: '14px' }}>
          <h2 id="legal-modal-title" className="font-display" style={{ margin: 0, fontSize: '18px', color: '#ecfdf5' }}>
            {doc.title}
          </h2>
          <button type="button" className="modal-close" onClick={onClose} aria-label="Κλείσιμο">
            ×
          </button>
        </div>
        <div style={{ display: 'grid', gap: '12px' }}>
          {doc.body.map((p) => (
            <p key={p.slice(0, 40)} style={{ margin: 0, fontSize: '13px', lineHeight: 1.65, color: '#cbd5e1' }}>
              {p}
            </p>
          ))}
        </div>
        <button type="button" className="btn-emerald" onClick={onClose} style={{ marginTop: '18px', width: '100%', padding: '12px' }}>
          Κλείσιμο
        </button>
      </div>
    </div>
  );
}

