export function customWeekTemplates(list) {
  const builtin = new Set(DEFAULT_WEEK_TEMPLATES.map((t) => t.id));
  const seen = new Set();
  const custom = [];
  (Array.isArray(list) ? list : []).forEach((tpl) => {
    if (!tpl?.id || builtin.has(tpl.id) || seen.has(tpl.id)) return;
    if (!tpl.plan || typeof tpl.plan !== 'object' || Array.isArray(tpl.plan)) return;
    seen.add(tpl.id);
    custom.push(tpl);
  });
  return custom;
}

/** Code defaults always win. localStorage may only add user templates. */
export function mergeWeekTemplates(stored) {
  return [...DEFAULT_WEEK_TEMPLATES, ...customWeekTemplates(stored)];
}
